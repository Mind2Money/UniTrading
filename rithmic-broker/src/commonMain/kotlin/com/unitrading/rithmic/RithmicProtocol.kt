/** Protocol-level failure: a Rithmic response code other than success, a reject frame or a dropped plant. */
class RithmicRemoteException(val code: String, message: String) : Exception(message)

internal fun ProtoMessage.rpCode(): List<String> = strings(Rf.RP_CODE)
internal fun ProtoMessage.userMsg(): String? = strings(Rf.USER_MSG).firstOrNull()
/** Dev kit 0.90 deprecated the 4-byte size fields for 8-byte `*_64` ones; a server may send either generation. */
internal fun ProtoMessage.size(field64: Int, field32: Int): Long? = long(field64) ?: long(field32)
internal fun ProtoMessage.timeMs(): Long? = long(Rf.SSBOE)?.takeIf { it > 0 }?.let { it * 1_000 + (long(Rf.USECS) ?: 0) / 1_000 }

/** Rithmic sends `rp_code` only on the terminal message of a reply; `"0"` is success, `"7"` is "no data". */
internal fun ProtoMessage.isTerminal(): Boolean = rpCode().isNotEmpty()
internal fun ProtoMessage.succeeded(): Boolean = rpCode().firstOrNull().let { it == "0" || it == "7" }
internal fun ProtoMessage.failureMessage(): String {
    val codes = rpCode()
    return safeRithmicMessage(codes.drop(1).joinToString(" ").ifBlank { "Rithmic 返回码 ${codes.firstOrNull() ?: "?"}" })
}

/** Server text is shown as-is apart from control characters and length; credentials are redacted where they are known. */
internal fun safeRithmicMessage(value: String): String = value.replace(Regex("[\\p{Cntrl}]"), " ").trim().take(300)
internal fun redactSecret(value: String, secret: String): String = if (secret.length < 4) value else value.replace(secret, "[redacted]")
